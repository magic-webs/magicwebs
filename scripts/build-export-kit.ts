// Embeds the renderer and page-schema source into packages/site-export, so a
// Next.js export ships the exact components that render pages on Magicwebs.
// Run after changing either package: `bun run export-kit`. A test fails while
// the embedded copy is stale.

import { readdirSync, readFileSync, writeFileSync } from "node:fs"
import path from "node:path"

const root = path.join(import.meta.dir, "..")

/** Source folders copied into the exported project, and where they land. */
const SOURCES = [
  { from: "packages/page-schema/src", to: "lib/magicwebs/page-schema" },
  { from: "packages/renderer/src", to: "lib/magicwebs/renderer", skip: ["server.tsx"] },
]

export function collectKit(): Record<string, string> {
  const kit: Record<string, string> = {}
  for (const source of SOURCES) {
    const dir = path.join(root, source.from)
    for (const file of readdirSync(dir).sort()) {
      if (!/\.tsx?$/.test(file) || /\.test\.tsx?$/.test(file) || source.skip?.includes(file)) continue
      kit[`${source.to}/${file}`] = readFileSync(path.join(dir, file), "utf8").replace(/\r\n/g, "\n")
    }
  }
  return kit
}

export const KIT_PATH = path.join(root, "packages/site-export/src/kit.generated.ts")

export function renderKit(kit: Record<string, string>): string {
  return `// Generated by scripts/build-export-kit.ts. Do not edit; run \`bun run export-kit\`.
export const KIT: Record<string, string> = ${JSON.stringify(kit, null, 1)}
`
}

if (import.meta.main) {
  writeFileSync(KIT_PATH, renderKit(collectKit()))
  console.log(`Wrote ${path.relative(root, KIT_PATH)}`)
}
