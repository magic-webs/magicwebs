// Generates the renderer's SVG data for ICON_NAMES (packages/page-schema/src/icons.ts)
// from Lucide's icon definitions. Run with `bun run icons` after changing the list.

import { readdirSync, readFileSync, writeFileSync } from "node:fs"
import path from "node:path"

import { ICON_NAMES } from "../packages/page-schema/src/icons"

const root = path.join(import.meta.dir, "..")
const store = path.join(root, "node_modules", ".bun")
const lucideDir = readdirSync(store).find((d) => d.startsWith("lucide-react@"))
if (!lucideDir) throw new Error("lucide-react is not installed; run bun install")
const iconsDir = path.join(store, lucideDir, "node_modules", "lucide-react", "dist", "esm", "icons")

type Node = [string, Record<string, string>][]
const camel = (name: string) => name.replace(/-([a-z])/g, (_, c: string) => c.toUpperCase())

const out: Record<string, Node> = {}
const missing: string[] = []
for (const name of ICON_NAMES) {
  let data: { node: Node } | undefined
  try {
    // Renamed icons are files that re-export the new name; follow them.
    let file = `${name}.mjs`
    for (let hops = 0; hops < 3; hops++) {
      const alias = readFileSync(path.join(iconsDir, file), "utf8").match(/export \{ default \} from '\.\/([^']+)'/)
      if (!alias) break
      file = alias[1]!
    }
    data = (await import(path.join(iconsDir, file))).__iconData
  } catch {
    // Reported below.
  }
  if (!data) {
    missing.push(name)
    continue
  }
  out[name] = data.node.map(([tag, attrs]) => [
    tag,
    Object.fromEntries(Object.entries(attrs).filter(([k]) => k !== "key").map(([k, v]) => [camel(k), String(v)])),
  ])
}
if (missing.length) throw new Error(`Not in Lucide: ${missing.join(", ")}`)

const target = path.join(root, "packages/renderer/src/icons.generated.ts")
writeFileSync(
  target,
  `// Generated by scripts/build-icons.ts from Lucide (https://lucide.dev). Do not edit.
//
// Lucide is ISC licensed: Copyright (c) Lucide Contributors 2022; portions
// Copyright (c) Cole Bemis 2013-2022 as part of Feather (MIT). Permission to use,
// copy, modify, and/or distribute this software for any purpose with or without
// fee is hereby granted, provided that the above copyright notice and this
// permission notice appear in all copies.
//
// Each icon is a list of SVG elements drawn in a 24×24 box with a 2px round stroke.
export const ICON_NODES: Record<string, [string, Record<string, string>][]> = ${JSON.stringify(out)}
`,
)
console.log(`Wrote ${Object.keys(out).length} icons to ${path.relative(root, target)}`)
